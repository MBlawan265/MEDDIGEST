async function seed() {
    try {
        await mongoose.connect(process.env.MONGODB_URI);
        console.log('Connected to DB');

        await Institution.deleteMany({});
        console.log('Cleared existing institutions');

        // Deduplicate in case list has duplicates
        const uniqueSchools = [...new Set(schools)];

        const docs = uniqueSchools.map(name => ({ name }));
        await Institution.insertMany(docs);
        console.log(`Seeded ${docs.length} institutions`);

        process.exit(0);
    } catch (err) {
        console.error(err);
        process.exit(1);
    }
}

seed();
